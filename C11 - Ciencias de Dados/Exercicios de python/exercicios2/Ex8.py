num1 = float(input("Digite um numero: "))
num2 = float(input("Digite um outro numero: "))

print("Adição: {}".format(num1 + num2))
print("Subtração: {}".format(num1 - num2))
print("Multiplicação: {}".format(num1 * num2))
print("Divisão: {}".format(num1 / num2))
print("Resto da divisão: {}".format(num1 % num2))
print("Potência: {}".format(num1 ** num2))
